package com.vladisx.youtubedownloader.data

import android.content.Context
import android.util.Log
import android.webkit.CookieManager
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.withContext
import java.io.File

object CookieStore {

    private const val TAG = "CookieStore"
    private const val FILE_NAME = "youtube-cookies.txt"

    private val _signedIn = MutableStateFlow(false)
    val signedIn: StateFlow<Boolean> = _signedIn.asStateFlow()

    private fun jarFile(context: Context): File = File(context.filesDir, FILE_NAME)

    fun cookiesFile(context: Context): File? =
        jarFile(context).takeIf { it.exists() && it.length() > 0 }

    fun refreshState(context: Context) {
        _signedIn.value = cookiesFile(context) != null
    }

    suspend fun capture(context: Context): Boolean = withContext(Dispatchers.IO) {
        runCatching {
            val manager = CookieManager.getInstance()
            val rawCookie = manager.getCookie("https://www.youtube.com") ?: ""
            val googleCookie = manager.getCookie("https://accounts.google.com") ?: ""
            val combined = "$rawCookie; $googleCookie"

            val lines = mutableListOf<String>()
            for (pair in combined.split(';')) {
                val trimmed = pair.trim()
                val eq = trimmed.indexOf('=')
                if (eq <= 0) continue

                val name = trimmed.substring(0, eq)
                val value = trimmed.substring(eq + 1)
                if (name.isBlank() || value.isBlank()) continue

                // Standard Netscape format line:
                // domain\tflag\tpath\tsecure\texpiry\tname\tvalue
                lines += ".youtube.com\tTRUE\t/\tTRUE\t2147483647\t$name\t$value"
                lines += ".google.com\tTRUE\t/\tTRUE\t2147483647\t$name\t$value"
            }

            if (lines.isEmpty()) {
                Log.w(TAG, "No cookies captured from WebView")
                return@withContext false
            }

            val file = jarFile(context)
            file.parentFile?.mkdirs()
            file.writeText(
                "# Netscape HTTP Cookie File\n" +
                    "# Generated by YouTubeDownloader in-app WebView\n" +
                    lines.distinct().joinToString("\n") + "\n"
            )

            Log.i(TAG, "Successfully captured ${lines.distinct().size} cookie entries to ${file.absolutePath}")
            _signedIn.value = true
            true
        }.getOrElse { t ->
            Log.e(TAG, "capture failed", t)
            false
        }
    }

    suspend fun signOut(context: Context) = withContext(Dispatchers.IO) {
        runCatching {
            CookieManager.getInstance().removeAllCookies(null)
            CookieManager.getInstance().flush()
            jarFile(context).delete()
            _signedIn.value = false
            Log.i(TAG, "signed out")
        }
    }
}
